"""Leakage checks and clean typical-abstract snapshots for fair evaluation."""
import json
import re
import shutil
import unicodedata
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable, Sequence


# Default snippet length used when scanning typical abstracts and accepted papers.
# 160 chars matches the 1.2 plan spec for "abstract 至少 160 字符片段匹配".
DEFAULT_MIN_ABSTRACT_CHARS = 160


@dataclass(frozen=True)
class LeakageReport:
    """Structured leakage report for typical abstracts and accepted papers."""

    summary: dict
    matches: list[dict]

    def to_dict(self) -> dict:
        return {"summary": self.summary, "matches": self.matches}


def load_papers_jsonl(path: str | Path) -> list[dict]:
    """Load evaluation papers from JSONL."""
    papers = []
    with Path(path).open("r", encoding="utf-8") as f:
        for line in f:
            if line.strip():
                papers.append(json.loads(line))
    return papers


def detect_typical_leakage(
    papers: Sequence[dict],
    typical_dir: str | Path,
    *,
    min_title_chars: int = 24,
    min_abstract_chars: int = DEFAULT_MIN_ABSTRACT_CHARS,
) -> LeakageReport:
    """Find test paper text that appears inside typical abstracts.

    Backward-compatible thin wrapper around :func:`detect_leakage`.
    """
    return detect_leakage(
        papers,
        typical_dir=typical_dir,
        accepted_paper_dir=None,
        min_title_chars=min_title_chars,
        min_abstract_chars=min_abstract_chars,
    )


def detect_leakage(
    papers: Sequence[dict],
    *,
    typical_dir: str | Path | None = None,
    accepted_paper_dir: str | Path | None = None,
    min_title_chars: int = 24,
    min_abstract_chars: int = DEFAULT_MIN_ABSTRACT_CHARS,
) -> LeakageReport:
    """Find test paper text that appears in typical abstracts and/or accepted papers.

    The scan is read-only: it does not modify any directory. The accepted-paper
    source is report-only (no cleaned accepted-paper snapshot is generated by
    :func:`build_clean_typical_snapshot`).
    """
    paper_needles = _paper_needles(
        papers,
        min_title_chars=min_title_chars,
        min_abstract_chars=min_abstract_chars,
    )

    matches: list[dict] = []
    leaked_typical_entries: set[tuple[str, int]] = set()
    leaked_accepted_entries: set[tuple[str, int]] = set()
    leaked_papers: set[int] = set()
    typical_file_count = 0
    accepted_file_count = 0

    if typical_dir is not None:
        typical_files = list(_iter_typical_files(typical_dir))
        typical_file_count = len(typical_files)
        for path in typical_files:
            data = _read_json(path)
            for idx, item in enumerate(data.get("abstracts", [])):
                haystack = _normalize_text(_entry_text(item))
                if not haystack:
                    continue
                for needle in paper_needles:
                    if needle["text"] in haystack:
                        leaked_typical_entries.add((path.name, idx))
                        leaked_papers.add(needle["paper_index"])
                        matches.append(
                            {
                                "source_type": "typical_abstract",
                                "paper_index": needle["paper_index"],
                                "paper_title": needle["paper_title"],
                                "paper_venue": needle["paper_venue"],
                                "match_type": needle["match_type"],
                                "typical_file": path.name,
                                "journal_id": data.get("journal_id") or path.stem,
                                "entry_index": idx,
                                "method_type": item.get("method_type", ""),
                                "novelty_level": item.get("novelty_level", ""),
                            }
                        )
                        break

    if accepted_paper_dir is not None:
        accepted_files = list(_iter_accepted_files(accepted_paper_dir))
        accepted_file_count = len(accepted_files)
        for path in accepted_files:
            data = _read_json(path)
            journal_id = data.get("journal_id") or path.stem
            for idx, item in enumerate(data.get("papers", [])):
                haystack = _normalize_text(_accepted_entry_text(item))
                if not haystack:
                    continue
                for needle in paper_needles:
                    if needle["text"] in haystack:
                        leaked_accepted_entries.add((path.name, idx))
                        leaked_papers.add(needle["paper_index"])
                        matches.append(
                            {
                                "source_type": "accepted_paper",
                                "paper_index": needle["paper_index"],
                                "paper_title": needle["paper_title"],
                                "paper_venue": needle["paper_venue"],
                                "match_type": needle["match_type"],
                                "accepted_paper_file": path.name,
                                "journal_id": journal_id,
                                "entry_index": idx,
                                "year": item.get("year", ""),
                                "source": item.get("source", ""),
                            }
                        )
                        break

    leaked_entry_count = len(leaked_typical_entries) + len(leaked_accepted_entries)

    summary = {
        "paper_count": len(papers),
        "typical_file_count": typical_file_count,
        "accepted_paper_file_count": accepted_file_count,
        "match_count": len(matches),
        "leaked_entry_count": leaked_entry_count,
        "leaked_paper_count": len(leaked_papers),
        "leaked_typical_entry_count": len(leaked_typical_entries),
        "leaked_accepted_paper_entry_count": len(leaked_accepted_entries),
    }
    return LeakageReport(summary=summary, matches=matches)


def build_clean_typical_snapshot(
    papers: Sequence[dict],
    typical_dir: str | Path,
    output_dir: str | Path,
    *,
    min_title_chars: int = 24,
    min_abstract_chars: int = DEFAULT_MIN_ABSTRACT_CHARS,
    overwrite: bool = True,
) -> LeakageReport:
    """Write a clean typical-abstract directory with leaked entries removed.

    This function only cleans typical abstracts. Accepted-paper leakage is
    detected (so the report can flag it) but the accepted-paper directory is
    not rewritten — it is report-only.
    """
    typical_dir = Path(typical_dir)
    output_dir = Path(output_dir)
    report = detect_typical_leakage(
        papers,
        typical_dir,
        min_title_chars=min_title_chars,
        min_abstract_chars=min_abstract_chars,
    )
    leaked_entries = {
        (match["typical_file"], match["entry_index"])
        for match in report.matches
        if match.get("source_type", "typical_abstract") == "typical_abstract"
    }

    if output_dir.exists():
        if not overwrite:
            raise FileExistsError(f"Output directory already exists: {output_dir}")
        shutil.rmtree(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    written = 0
    removed = 0
    for path in _iter_typical_files(typical_dir):
        data = _read_json(path)
        clean_abstracts = []
        for idx, item in enumerate(data.get("abstracts", [])):
            if (path.name, idx) in leaked_entries:
                removed += 1
                continue
            clean_abstracts.append(item)
        data["abstracts"] = clean_abstracts
        (output_dir / path.name).write_text(
            json.dumps(data, ensure_ascii=False, indent=2),
            encoding="utf-8",
        )
        written += 1

    summary = dict(report.summary)
    summary.update(
        {
            "removed_entry_count": removed,
            "written_file_count": written,
            "source_typical_dir": str(typical_dir),
            "clean_typical_dir": str(output_dir),
        }
    )
    return LeakageReport(summary=summary, matches=report.matches)


def write_report(report: LeakageReport, output_path: str | Path) -> None:
    """Persist a leakage report as JSON."""
    path = Path(output_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(report.to_dict(), ensure_ascii=False, indent=2),
        encoding="utf-8",
    )


def _paper_needles(
    papers: Sequence[dict],
    *,
    min_title_chars: int,
    min_abstract_chars: int,
) -> list[dict]:
    needles = []
    for idx, paper in enumerate(papers):
        title = (paper.get("title") or "").strip()
        normalized_title = _normalize_text(title)
        if len(normalized_title) >= min_title_chars:
            needles.append(
                {
                    "paper_index": idx,
                    "paper_title": title,
                    "paper_venue": paper.get("venue", ""),
                    "match_type": "title",
                    "text": normalized_title,
                }
            )

        abstract = _normalize_text(paper.get("abstract") or "")
        if len(abstract) >= min_abstract_chars:
            needles.append(
                {
                    "paper_index": idx,
                    "paper_title": title,
                    "paper_venue": paper.get("venue", ""),
                    "match_type": "abstract_snippet",
                    "text": abstract[:min_abstract_chars],
                }
            )
    return needles


def _iter_typical_files(typical_dir: str | Path) -> Iterable[Path]:
    base = Path(typical_dir)
    if not base.exists():
        return []
    return sorted(base.glob("*.json"))


def _iter_accepted_files(accepted_paper_dir: str | Path) -> Iterable[Path]:
    base = Path(accepted_paper_dir)
    if not base.exists():
        return []
    return sorted(base.glob("*.json"))


def _read_json(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def _entry_text(item: dict) -> str:
    return " ".join(
        str(item.get(field) or "")
        for field in ("title", "paper_title", "source_title", "abstract", "text")
    )


def _accepted_entry_text(item: dict) -> str:
    return " ".join(
        str(item.get(field) or "") for field in ("title", "abstract")
    )


def _normalize_text(text: str) -> str:
    text = unicodedata.normalize("NFKD", str(text)).lower()
    text = re.sub(r"[^a-z0-9]+", " ", text)
    return re.sub(r"\s+", " ", text).strip()
